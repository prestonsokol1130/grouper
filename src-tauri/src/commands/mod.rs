//! Tauri commands invoked from the frontend, and their TypeScript bindings.

pub mod app_cmds;
pub mod icon_cmds;
pub mod launch_cmds;
pub mod scan_cmds;
pub mod shortcut_cmds;
pub mod state_cmds;

use tauri_specta::{collect_commands, Builder};

use crate::state::AppState;

/// Every command the frontend can call, registered for both Tauri and the
/// generated bindings in `src/bindings/index.ts`.
pub fn specta_builder() -> Builder<tauri::Wry> {
    Builder::<tauri::Wry>::new()
        .commands(collect_commands![
            state_cmds::get_state,
            state_cmds::create_group,
            state_cmds::rename_group,
            state_cmds::delete_group,
            state_cmds::set_group_apps,
            state_cmds::update_settings,
            state_cmds::set_launchpad_layout,
            scan_cmds::rescan_apps,
            icon_cmds::get_cache_dir,
            launch_cmds::launch_app,
            launch_cmds::launch_group,
            app_cmds::pick_and_add_apps,
            app_cmds::add_app_from_path,
            app_cmds::remove_app,
            shortcut_cmds::create_group_shortcut,
            shortcut_cmds::reveal_group_shortcut,
        ])
        .typ::<AppState>()
}

#[cfg(test)]
mod tests {
    use specta_typescript::Typescript;

    /// Regenerates `src/bindings/index.ts`. Run `cargo test` after changing
    /// any command or state type, then commit the regenerated file.
    #[test]
    fn export_bindings() {
        let path = concat!(env!("CARGO_MANIFEST_DIR"), "/../src/bindings/index.ts");
        super::specta_builder()
            .export(
                Typescript::default().header("// Generated by tauri-specta. Do not edit.\n"),
                path,
            )
            .unwrap();
    }
}
